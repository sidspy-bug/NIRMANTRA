"""
Unit tests for the PdfExtractor.

Uses synthetic PDFs generated by fixtures (no external test files needed).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from nirmantra_ai.document.errors import (
    FileNotFoundError_,
    UnsupportedFormatError,
)
from nirmantra_ai.document.models import Confidence, ExtractionMethod
from nirmantra_ai.document.pdf_extractor import PdfExtractor


@pytest.fixture
def extractor() -> PdfExtractor:
    return PdfExtractor(max_pages=100)


class TestPdfExtractorSuccess:
    """Happy-path tests for digital PDF extraction."""

    def test_extracts_text_from_two_page_pdf(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_text_pdf)

        assert result.source_filename == "test_building_plan.pdf"
        assert result.total_pages == 2
        assert result.processed_pages == 2
        assert result.is_complete
        assert result.method == ExtractionMethod.DIGITAL
        assert len(result.pages) == 2

    def test_page_one_contains_building_info(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_text_pdf)
        page1 = result.pages[0]

        assert page1.page_number == 1
        assert "Test Residential Complex" in page1.text
        assert "1200" in page1.text
        assert page1.method == ExtractionMethod.DIGITAL
        assert page1.confidence == Confidence.HIGH

    def test_page_two_contains_fire_safety(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_text_pdf)
        page2 = result.pages[1]

        assert page2.page_number == 2
        assert "Fire Safety" in page2.text or "Fire extinguishers" in page2.text
        assert "setback" in page2.text.lower()

    def test_full_text_contains_all_content(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_text_pdf)
        full = result.full_text

        assert "[Page 1]" in full
        assert "[Page 2]" in full
        assert "Test Residential Complex" in full

    def test_extraction_result_has_timestamp(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_text_pdf)
        assert result.extracted_at is not None


class TestPdfExtractorEdgeCases:
    """Edge cases and warning detection."""

    def test_empty_pdf_produces_warnings(
        self, extractor: PdfExtractor, tmp_empty_pdf: Path
    ) -> None:
        result = extractor.extract(tmp_empty_pdf)

        assert result.total_pages == 1
        assert result.processed_pages == 1
        assert result.has_warnings
        assert any(w.code == "empty_page" for w in result.warnings)

    def test_serialization_round_trip(
        self, extractor: PdfExtractor, tmp_text_pdf: Path
    ) -> None:
        """Ensure the result can be serialized to JSON and back."""
        result = extractor.extract(tmp_text_pdf)
        data = result.model_dump(mode="json")
        from nirmantra_ai.document.models import ExtractionResult

        restored = ExtractionResult.model_validate(data)
        assert restored.total_pages == result.total_pages
        assert len(restored.pages) == len(result.pages)


class TestPdfExtractorErrors:
    """Error handling and validation."""

    def test_rejects_nonexistent_file(self, extractor: PdfExtractor) -> None:
        with pytest.raises(FileNotFoundError_):
            extractor.extract("/nonexistent/file.pdf")

    def test_rejects_non_pdf_file(
        self, extractor: PdfExtractor, tmp_non_pdf: Path
    ) -> None:
        with pytest.raises(UnsupportedFormatError):
            extractor.extract(tmp_non_pdf)

    def test_rejects_oversized_pdf(self, tmp_text_pdf: Path) -> None:
        """A PDF with more pages than max_pages should be rejected."""
        from nirmantra_ai.document.errors import PageLimitExceededError

        tiny_extractor = PdfExtractor(max_pages=1)
        with pytest.raises(PageLimitExceededError) as exc_info:
            tiny_extractor.extract(tmp_text_pdf)
        assert exc_info.value.page_count == 2
        assert exc_info.value.limit == 1
